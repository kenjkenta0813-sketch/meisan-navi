Object.entries(localSpecialties).forEach(([prefectureName, municipalities]) => {
  const prefectureCatalog = [];
  const knownNames = new Set();
  Object.values(municipalities).flat().forEach(product => {
    if (knownNames.has(product[0])) return;
    knownNames.add(product[0]);
    prefectureCatalog.push(product);
  });

  Object.entries(municipalities).forEach(([municipalityName, originalProducts]) => {
    const expanded = [...originalProducts];
    const selectedNames = new Set(expanded.map(product => product[0]));

    prefectureCatalog.forEach(([name, , icon]) => {
      if (expanded.length >= 15 || selectedNames.has(name)) return;
      selectedNames.add(name);
      expanded.push([name, `${prefectureName}内のお取り寄せ候補として紹介しています。`, icon]);
    });

    orderCandidateCategories.forEach(([category, icon]) => {
      if (expanded.length >= 15) return;
      const name = `${municipalityName}の${category}`;
      if (selectedNames.has(name)) return;
      selectedNames.add(name);
      expanded.push([name, "地域の商品を探すためのお取り寄せ検索候補です。", icon]);
    });

    municipalities[municipalityName] = expanded.slice(0, 15);
  });
});

const prefecture = document.querySelector("#prefecture");
const city = document.querySelector("#city");
const result = document.querySelector("#result");
const template = document.querySelector("#product-template");

Object.keys(localSpecialties).forEach(name => prefecture.add(new Option(name, name)));

prefecture.addEventListener("change", () => {
  city.replaceChildren();
  const selected = localSpecialties[prefecture.value];
  if (!selected) {
    city.add(new Option("先に都道府県を選択", ""));
    city.disabled = true;
    return;
  }
  city.add(new Option("市町村を選択", ""));
  Object.keys(selected).forEach(name => city.add(new Option(name, name)));
  city.disabled = false;
});

function showResult(pref, municipality) {
  const products = localSpecialties[pref]?.[municipality];
  if (!products) return;
  result.replaceChildren();
  const kicker = document.createElement("p");
  kicker.className = "result-kicker";
  kicker.textContent = `${pref}・${municipality}`;
  const heading = document.createElement("h2");
  heading.textContent = `名産品・お取り寄せ候補 ${products.length}選`;
  const note = document.createElement("p");
  note.className = "result-note";
  note.textContent = "市の代表品を先に掲載し、不足分は県内の名産品や地域の商品検索候補を紹介しています。価格・送料・販売元をご確認のうえ購入してください。";
  const list = document.createElement("div");
  list.className = "product-list";
  products.forEach(([name, description, icon]) => {
    const item = template.content.cloneNode(true);
    item.querySelector(".product-icon").textContent = icon;
    item.querySelector("h3").textContent = name;
    item.querySelector("p").textContent = description;
    const query = `${pref} ${municipality} ${name}`;
    const rakuten = item.querySelector(".order-rakuten");
    const yahoo = item.querySelector(".order-yahoo");
    rakuten.href = `https://search.rakuten.co.jp/search/mall/${encodeURIComponent(query)}/`;
    yahoo.href = `https://shopping.yahoo.co.jp/search?p=${encodeURIComponent(query)}`;
    item.querySelector(".order-amazon").href = `https://www.amazon.co.jp/s?k=${encodeURIComponent(name)}`;
    item.querySelector(".order-jatown").href = `https://www.google.com/search?q=${encodeURIComponent("site:ja-town.com " + name)}`;
    item.querySelector(".order-furusato").href = `https://www.google.com/search?q=${encodeURIComponent("site:furusato-tax.jp " + query)}`;
    list.append(item);
  });
  result.append(kicker, heading, note, list);
  result.hidden = false;
  result.scrollIntoView({ behavior: "smooth", block: "start" });
}

document.querySelector("#search-form").addEventListener("submit", event => {
  event.preventDefault();
  showResult(prefecture.value, city.value);
});

